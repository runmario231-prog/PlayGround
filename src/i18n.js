let current = 'en';

export function detectLang() {
  try {
    const saved = JSON.parse(localStorage.getItem('clockwork.v1') || 'null');
    if (saved?.settings?.lang) return saved.settings.lang;
  } catch { /* ignore */ }
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('ar') ? 'ar' : 'en';
}

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  let s = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function pieceName(p) {
  return p?.name?.[current] || p?.name?.en || '';
}

export function pieceDesc(p) {
  return p?.desc?.[current] || p?.desc?.en || '';
}

export function pieceHint(p) {
  return p?.hint?.[current] || p?.hint?.en || '';
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const key = el.dataset.i18n;
    const vars = el.dataset.i18nVars ? JSON.parse(el.dataset.i18nVars) : null;
    el.textContent = t(key, vars);
  }
  for (const el of root.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  }
}
